const stored = localStorage.getItem('lauftrainer-locale') as Locale | null
const locale = ref<Locale>(stored === 'en' || (!stored && navigator.language.toLowerCase().startsWith('en')) ? 'en' : 'de')

export function useI18n() {
    const t = computed(() => translations[locale.value]);
    const setLocale = (value: Locale) => {
        locale.value = value;
        localStorage.setItem('lauftrainer-locale', value)
    };
    const formatTime = (date: Date) => date.toLocaleTimeString(locale.value === 'de' ? 'de-DE' : 'en-US', {
        hour: '2-digit',
        minute: '2-digit'
    });
    return {locale, t, setLocale, formatTime}
}
